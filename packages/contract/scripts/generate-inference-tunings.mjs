#!/usr/bin/env node
// Generates apps/inference/src/inference/generated/tunings.py from the
// "inference" section of packages/contract/config.json. Plain node, no deps.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const contractDir = dirname(dirname(fileURLToPath(import.meta.url)));
const configPath = join(contractDir, "config.json");
const outputPath = join(
  contractDir,
  "..",
  "..",
  "apps",
  "inference",
  "src",
  "inference",
  "generated",
  "tunings.py",
);

const config = JSON.parse(readFileSync(configPath, "utf8"));
const inference = config.inference;
if (!inference?.ctc || !inference?.smooth) {
  throw new Error(
    "config.json is missing the inference.ctc / inference.smooth sections",
  );
}

const toSnakeCase = (key) => key.replace(/([A-Z])/g, "_$1").toLowerCase();

const toPyValue = (key, value) => {
  if (typeof value === "number" && Number.isFinite(value)) {
    return String(value);
  }
  if (Array.isArray(value) && value.every((item) => typeof item === "string")) {
    return `(${value.map((item) => JSON.stringify(item)).join(", ")}${value.length === 1 ? "," : ""})`;
  }
  throw new Error(
    `inference tuning "${key}" must be a finite number or string list, got: ${value}`,
  );
};

const toPyType = (value) => {
  if (Array.isArray(value)) return "tuple[str, ...]";
  return Number.isInteger(value) ? "int" : "float";
};

const toPyDataclass = (className, instanceName, section) => {
  const entries = Object.entries(section).map(
    ([key, value]) =>
      `    ${toSnakeCase(key)}: ${toPyType(value)} = ${toPyValue(key, value)}`,
  );
  return `@dataclass(frozen=True)\nclass ${className}:\n${entries.join("\n")}\n\n\n${instanceName} = ${className}()`;
};

const moduleSource = `# generated by packages/contract/scripts/generate-inference-tunings.mjs - do not edit.
# Source of truth: the "inference" section of packages/contract/config.json.
# Regenerate with: moon run contract:generateTunings

from dataclasses import dataclass

${toPyDataclass("CtcTunings", "CTC", inference.ctc)}

${toPyDataclass("SmoothTunings", "SMOOTH", inference.smooth)}
`;

writeFileSync(outputPath, moduleSource);
console.log(`wrote ${relative(process.cwd(), outputPath)}`);
